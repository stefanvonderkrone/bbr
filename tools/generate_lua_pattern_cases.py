#!/usr/bin/env python3
"""Generate the Lua pattern cases that prove the RE2 translation of `tools/adapt_queries.py`.

Usage: generate_lua_pattern_cases.py NVIM_TREESITTER_ROOT [--lua luajit]

The cases are every `#lua-match?` and `#not-lua-match?` pattern in the M27 queries and their bases,
and extra patterns for the forms that those queries do not use. LuaJIT, the Lua of Neovim, gives the
expected result of `string.find` for each sample. The Zig test compiles each translation with RE2 and
compares its result with the Lua result.
"""

import argparse
import importlib.util
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/highlight/lua_pattern_cases.zig"
spec = importlib.util.spec_from_file_location("adapt_queries", ROOT / "tools/adapt_queries.py")
adapter = importlib.util.module_from_spec(spec)
spec.loader.exec_module(adapter)

QUERIES = (
    "zig c cpp c_sharp php php_only python rust odin swift kotlin java groovy toml dockerfile make ruby "
    "html html_tags xml markdown markdown_inline sql"
).split()
LUA_PREDICATES = frozenset({"#lua-match?", "#not-lua-match?"})
EXTRA_PATTERNS = (
    "^a.-b$",
    "<.->",
    "%a+",
    "%A",
    "%c",
    "%C",
    "%d%D",
    "%l+%L",
    "%p",
    "%P+$",
    "%s%S",
    "%u%U",
    "%w+%W",
    "%x+$",
    "^%X",
    "[%w_]+",
    "[^%s]+",
    "[a-c%.]",
    "[]]",
    "[^]x]",
    "%.%-%%",
    "^%[.*%]$",
    "a?b+c*",
    "x$y",
)
SAMPLES = (
    "",
    "a",
    "A",
    "z9",
    "ab",
    "acb",
    "a\nb",
    "aXb_",
    "<x>y>",
    "ABC_1",
    "Abc",
    "__init__",
    "__FILE__",
    "_Foo",
    "m_value",
    "onclick",
    "onClick",
    "preg_match",
    "__builtin_expect",
    "123",
    "-1.5",
    "1.",
    "/// doc",
    "///",
    "////",
    "//! inner",
    "/** doc */",
    "/*! x",
    "#!/bin/sh",
    "#: tag",
    "#  @rbs x",
    "# | x",
    "elif x",
    "else",
    " lang = x",
    "<a type =",
    "${x}",
    "(x",
    "(\n",
    "x)",
    "a )",
    "[x]",
    "]",
    "a.-%",
    "x$y",
    "\t\x01",
    "\x7f",
    "é",
    "aé",
    "Ωmega",
    "!?",
    "ff0A",
)


def lua_patterns(raw_root):
    found = set()
    for name in QUERIES:
        for kind in adapter.KINDS:
            if not (raw_root / name / f"{kind}.scm").is_file():
                continue
            for source_name, text in adapter.sources(name, kind, raw_root):
                collect(adapter.parse(text, f"{source_name}/{kind}.scm"), found)
    return found


def collect(items, found):
    for item in items:
        if not isinstance(item, adapter.Form):
            continue
        head = item.predicate()
        if head is not None and head.text in LUA_PREDICATES:
            found.add(adapter.decode_string(item.words()[2].text))
        elif head is None:
            collect(item.items, found)


def lua_hex(value):
    return '"' + "".join(f"\\{byte}" for byte in value.encode()) + '"'


def lua_results(lua, patterns):
    script = ["local samples = {" + ",".join(lua_hex(sample) for sample in SAMPLES) + "}"]
    for pattern in patterns:
        script.append(
            "do local r = {} for i, s in ipairs(samples) do r[i] = string.find(s, "
            + lua_hex(pattern)
            + ') and "1" or "0" end print(table.concat(r)) end'
        )
    output = subprocess.run([lua, "-"], input="\n".join(script), capture_output=True, text=True, check=True)
    return output.stdout.split()


def zig_string(value):
    out = []
    for byte in value.encode():
        char = chr(byte)
        if char in '"\\':
            out.append("\\" + char)
        elif 0x20 <= byte < 0x7F:
            out.append(char)
        else:
            out.append(f"\\x{byte:02x}")
    return '"' + "".join(out) + '"'


def render(patterns, results):
    lines = [
        "//! Generated by `python3 tools/generate_lua_pattern_cases.py`. Do not edit.",
        "//! `matches` holds the LuaJIT `string.find` result of the pattern for each sample, 1 for a match.",
        "",
        "pub const Case = struct { lua: []const u8, re2: []const u8, matches: *const [samples.len]u8 };",
        "",
        "pub const samples = [_][]const u8{",
        *(f"    {zig_string(sample)}," for sample in SAMPLES),
        "};",
        "",
        "pub const cases = [_]Case{",
        *(
            f"    .{{ .lua = {zig_string(pattern)}, .re2 = {zig_string(adapter.lua_to_re2(pattern))}, .matches = {zig_string(result)} }},"
            for pattern, result in zip(patterns, results)
        ),
        "};",
        "",
    ]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("raw_root", type=Path, help="nvim-treesitter runtime/queries directory")
    parser.add_argument("--lua", default="luajit")
    arguments = parser.parse_args()
    patterns = sorted(lua_patterns(arguments.raw_root) | set(EXTRA_PATTERNS))
    results = lua_results(arguments.lua, patterns)
    if len(results) != len(patterns) or any(len(result) != len(SAMPLES) for result in results):
        print("unexpected Lua output", file=sys.stderr)
        return 1
    OUTPUT.write_text(render(patterns, results), encoding="utf-8")
    print(f"wrote {len(patterns)} patterns and {len(SAMPLES)} samples to {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
